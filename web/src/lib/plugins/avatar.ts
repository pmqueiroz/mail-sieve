export const PLUGIN_COLORS = { gray: 0, red: 25, orange: 55, yellow: 92, green: 150, teal: 190, blue: 250, violet: 295, pink: 350 } as const;

export type PluginIcon = keyof typeof PLUGIN_ICONS;
export type PluginColor = keyof typeof PLUGIN_COLORS;

export interface PluginAvatarSpec {
  icon?: string | null;
  color?: string | null;
}

export interface ResolvedAvatar {
  paths: readonly string[] | null;
  monogram: string;
  hue: number;
  chroma: number;
}

const FALLBACK_COLORS = (Object.keys(PLUGIN_COLORS) as PluginColor[]).filter((color) => color !== 'gray');

function hash(key: string): number {
  let value = 0;
  for (const char of key) value = (value * 31 + char.charCodeAt(0)) >>> 0;
  return value;
}

function isIcon(value: string | null | undefined): value is PluginIcon {
  return !!value && Object.hasOwn(PLUGIN_ICONS, value);
}

function isColor(value: string | null | undefined): value is PluginColor {
  return !!value && Object.hasOwn(PLUGIN_COLORS, value);
}

export function monogram(name: string): string {
  const words = name.trim().split(/\s+/).filter(Boolean).slice(0, 2);
  return words.map((word) => word.charAt(0).toUpperCase()).join('') || '?';
}

export function resolveAvatar(spec: PluginAvatarSpec | null, id: string, name: string): ResolvedAvatar {
  const icon = spec?.icon;
  const chosen = spec?.color;
  const paths = isIcon(icon) ? PLUGIN_ICONS[icon] : null;
  const color: PluginColor = isColor(chosen) ? chosen : (FALLBACK_COLORS[hash(id) % FALLBACK_COLORS.length] ?? 'gray');
  return { paths, monogram: monogram(name), hue: PLUGIN_COLORS[color], chroma: color === 'gray' ? 0 : 1 };
}
